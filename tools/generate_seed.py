"""Regenerate db/init/002_seed.sql and data/activity_daily.csv.

The output is deterministic (fixed random seed), so re-running it produces
identical files. Run from the repo root:

    python3 tools/generate_seed.py
"""

import csv
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAST_DAY = date(2026, 10, 4)  # the day before the scenario's Monday 5 October 2026
DAYS = 14

USERS = [
    ("u_owner_alex", "alex@example.com", "Alex Cheng", "owner"),
    ("u_owner_mai", "mai@example.com", "Mai Tanaka", "owner"),
    ("u_vet_som", "som.vet@example.com", "Dr Som Rattana", "vet"),
    ("u_admin_kim", "kim.admin@example.com", "Kim Admin", "admin"),
]

PETS = [
    # id, owner, name, species, breed, sex, neutered, birth_date, weight_kg, notes
    ("p_lucky", "u_owner_alex", "Lucky", "cat", "Domestic shorthair", "male", True,
     "2019-03-14", 5.2, "Indoor only. Had one urinary infection in 2024."),
    ("p_bobby", "u_owner_alex", "Bobby", "dog", "Beagle", "male", True,
     "2021-07-02", 13.8, "Food-motivated. Vet advised weight watch."),
    ("p_mochi", "u_owner_mai", "Mochi", "dog", "Shiba Inu", "female", True,
     "2022-11-20", 9.1, None),
]

# Typical daily minutes per pet: (lying, sitting, standing, walking)
BASELINE = {
    "p_lucky": (980, 210, 95, 45),
    "p_bobby": (870, 190, 160, 95),
    "p_mochi": (840, 170, 175, 120),
}


def activity_rows():
    rng = random.Random(20261005)
    rows = []
    for pet_id, (lying, sitting, standing, walking) in BASELINE.items():
        for offset in range(DAYS - 1, -1, -1):
            day = LAST_DAY - timedelta(days=offset)
            jitter = lambda v, pct=0.08: max(0, round(v * (1 + rng.uniform(-pct, pct))))
            l, s, st, w = jitter(lying), jitter(sitting), jitter(standing), jitter(walking, 0.12)
            # Lucky walks much less over the last three days: a pattern worth noticing.
            if pet_id == "p_lucky" and offset < 3:
                w = round(w * 0.4)
                l += 40
            rows.append((pet_id, day.isoformat(), l, s, st, w))
    return rows


def sql_literal(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    rows = activity_rows()
    lines = ["-- Generated by tools/generate_seed.py. Do not edit by hand.", ""]
    lines.append("INSERT INTO users (id, email, display_name, role) VALUES")
    lines.append(",\n".join("    (" + ", ".join(map(sql_literal, u)) + ")" for u in USERS) + ";")
    lines.append("")
    lines.append("INSERT INTO pets (id, owner_id, name, species, breed, sex, neutered, birth_date, weight_kg, notes) VALUES")
    lines.append(",\n".join("    (" + ", ".join(map(sql_literal, p)) + ")" for p in PETS) + ";")
    lines.append("")
    lines.append("INSERT INTO activity_daily (pet_id, day, lying_min, sitting_min, standing_min, walking_min) VALUES")
    lines.append(",\n".join("    (" + ", ".join(map(sql_literal, r)) + ")" for r in rows) + ";")
    (ROOT / "db/init/002_seed.sql").write_text("\n".join(lines) + "\n")

    with open(ROOT / "data/activity_daily.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["pet_id", "day", "lying_min", "sitting_min", "standing_min", "walking_min"])
        w.writerows(rows)


if __name__ == "__main__":
    main()
